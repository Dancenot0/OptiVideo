    @staticmethod
    def get_icon(svg_str, color="#ffffff", size=QSize(24, 24)):
        # Inject color into SVG
        colored_svg = svg_str.replace('currentColor', color)
        renderer = QSvgRenderer(colored_svg.encode('utf-8'))
        pixmap = QPixmap(size)
        pixmap.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pixmap)
        renderer.render(painter)
        painter.end()
        return QIcon(pixmap)
